//! Diagnostic names for the frame trace: the protocol's GL functions and the GL
//! enumerants (at least 0x100) the host engine refers to, one name per value,
//! the unsuffixed core name preferred. Values below 0x100 are context-dependent
//! (primitive modes, blend factors, booleans) and are named by argument kind.
use crate::gl_api::*;

macro_rules! names {
    ($value:expr, $prefix:literal; $($name:ident,)*) => {
        match $value {
            $($name => Some(&stringify!($name)[$prefix..]),)*
            _ => None,
        }
    };
}

